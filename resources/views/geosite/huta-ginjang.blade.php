<script>
    let currentImageIndex = 0;
    let currentZoom = 1;
    let currentPanX = 0;
    let currentPanY = 0;

    function initLightboxImages() {
        return Array.from(document.querySelectorAll('.galeri-item:not([style*="display:none"]) img'));
    }

    function openLightbox(img) {
        const lightbox = document.getElementById('lightbox');
        const lightboxImg = document.getElementById('lightboxImg');
        const allImages = Array.from(document.querySelectorAll('.galeri-item img'));
        currentImageIndex = allImages.indexOf(img);
        lightboxImg.src = img.src;
        lightbox.classList.add('active');
        document.body.style.overflow = 'hidden';
        resetLightboxZoom();
        updateLightboxCounter();
    }

    function closeLightbox() {
        const lightbox = document.getElementById('lightbox');
        lightbox.classList.remove('active');
        document.body.style.overflow = '';
        resetLightboxZoom();
    }

    function zoomLightboxImage(delta) {
        const newZoom = currentZoom + delta;
        if (newZoom >= 1 && newZoom <= 3) {
            currentZoom = newZoom;
            updateLightboxImage();
        }
    }

    function resetLightboxZoom() {
        currentZoom = 1;
        currentPanX = 0;
        currentPanY = 0;
        updateLightboxImage();
    }

    function updateLightboxImage() {
        const img = document.getElementById('lightboxImg');
        if (!img) return;
        img.style.transform = `scale(${currentZoom}) translate(${currentPanX}px, ${currentPanY}px)`;
        document.getElementById('zoomLevel').textContent = Math.round(currentZoom * 100) + '%';
    }

    function nextLightboxImage() {
        const allImages = initLightboxImages();
        currentImageIndex = (currentImageIndex + 1) % allImages.length;
        openLightbox(allImages[currentImageIndex]);
    }

    function prevLightboxImage() {
        const allImages = initLightboxImages();
        currentImageIndex = (currentImageIndex - 1 + allImages.length) % allImages.length;
        openLightbox(allImages[currentImageIndex]);
    }

    function updateLightboxCounter() {
        const allImages = initLightboxImages();
        document.getElementById('lightboxCounter').textContent = (currentImageIndex + 1) + '/' + allImages.length;
    }

    document.addEventListener('DOMContentLoaded', function() {
        document.querySelectorAll('.galeri-item img').forEach(function(img) {
            img.addEventListener('click', function() {
                openLightbox(this);
            });
        });

        const lightbox = document.getElementById('lightbox');
        if (lightbox) {
            lightbox.addEventListener('click', function(e) {
                if (e.target === lightbox) closeLightbox();
            });
        }

        document.addEventListener('keydown', function(e) {
            if (document.getElementById('lightbox')?.classList.contains('active')) {
                if (e.key === 'ArrowRight') nextLightboxImage();
                if (e.key === 'ArrowLeft') prevLightboxImage();
                if (e.key === 'Escape') closeLightbox();
                if (e.key === '+' || e.key === '=') zoomLightboxImage(0.1);
                if (e.key === '-') zoomLightboxImage(-0.1);
            }
        });

        document.querySelectorAll('.tab-btn').forEach(function(btn) {
            btn.addEventListener('click', function() {
                document.querySelectorAll('.tab-btn').forEach(function(b) {
                    b.classList.remove('active');
                });
                btn.classList.add('active');
                const tab = btn.dataset.tab;
                document.querySelectorAll('.galeri-item').forEach(function(item) {
                    item.style.display = item.classList.contains(tab) ? 'block' : 'none';
                });
                resetLightboxZoom();
            });
        });

        function getHashFromAnchor(anchor) {
            const href = anchor.getAttribute('href');
            if (!href) return null;
            if (href.startsWith('#')) return href;
            try {
                const url = new URL(href, window.location.origin);
                if (url.pathname === window.location.pathname) return url.hash;
            } catch (error) {
                return null;
            }
            return null;
        }

        document.querySelectorAll('a[href*="#"]').forEach(function(anchor) {
            const hash = getHashFromAnchor(anchor);
            if (!hash) return;
            anchor.addEventListener('click', function(e) {
                if (window.location.pathname !== new URL(anchor.href, window.location.origin).pathname) return;
                if (!hash) return;
                e.preventDefault();
                const target = document.querySelector(hash);
                if (target) {
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                    history.replaceState(null, '', hash);
                }
            });
        });

        if (window.location.hash) {
            setTimeout(function() {
                const target = document.querySelector(window.location.hash);
                if (target) {
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }
            }, 200);
        }
    });
</script>
